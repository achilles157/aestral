  /// Year Pillar — Li Chun (立春) boundary from lookup table, not fixed Feb 4.
  static BaziPillar getYearPillar(int year, int month, int day) {
    final int liChunDay = _getJieDay(1, year); // index 1 = Li Chun
    final int adjustedYear = (month < 2 || (month == 2 && day < liChunDay))
        ? year - 1
        : year;
    final int stemIndex = ((adjustedYear - 4) % 10 + 10) % 10;
    final int branchIndex = ((adjustedYear - 4) % 12 + 12) % 12;
    return _buildPillar(stemIndex, branchIndex);
  }

  /// Returns the Earthly Branch index for the Ba Zi month containing the date.
  /// Uses actual solar term day for [year] (not fixed approximation).
  static int _monthBranchIndex(int month, int day, int year) {
    final int md = month * 100 + day;
    if (md < 100 + _getJieDay(0, year)) return 0; // < XiaoHan : Rat
    if (md < 200 + _getJieDay(1, year)) return 1; // < LiChun  : Ox
    if (md < 300 + _getJieDay(2, year)) return 2; // < JingZhe : Tiger
    if (md < 400 + _getJieDay(3, year)) return 3; // < QingMing: Rabbit
    if (md < 500 + _getJieDay(4, year)) return 4; // < LiXia   : Dragon
    if (md < 600 + _getJieDay(5, year)) return 5; // < MangZhong: Snake
    if (md < 700 + _getJieDay(6, year)) return 6; // < XiaoShu : Horse
    if (md < 800 + _getJieDay(7, year)) return 7; // < LiQiu   : Goat
    if (md < 900 + _getJieDay(8, year)) return 8; // < BaiLu   : Monkey
    if (md < 1000 + _getJieDay(9, year)) return 9; // < HanLu   : Rooster
    if (md < 1100 + _getJieDay(10, year)) return 10; // < LiDong  : Dog
    if (md < 1200 + _getJieDay(11, year)) return 11; // < DaXue   : Pig
    return 0; // DaXue+   : Rat
  }

  /// Month Pillar — branch from solar term, stem from year stem.
  static BaziPillar getMonthPillar(
    int month,
    int day,
    int yearStemIndex,
    int year,
  ) {
    final int monthBranchIndex = _monthBranchIndex(month, day, year);
    final int tigerStemStart = (yearStemIndex % 5) * 2 + 2;
    final int monthSequence = (monthBranchIndex - 2 + 12) % 12;
    final int monthStemIndex = (tigerStemStart + monthSequence) % 10;
    return _buildPillar(monthStemIndex, monthBranchIndex);
  }

  /// Day Pillar — JDN reference: 1 Jan 2000 = Geng (6) Chen (4).
  static BaziPillar getDayPillar(int year, int month, int day) {
    final int jdn = dateToJdn(year, month, day);
    final int stemIndex = ((jdn - 2451545 + 6) % 10 + 10) % 10;
    final int branchIndex = ((jdn - 2451545 + 4) % 12 + 12) % 12;
    return _buildPillar(stemIndex, branchIndex);
  }

  /// Hour Pillar — 12 two-hour shi blocks, Zi starts at 23:00.
  static BaziPillar getHourPillar(int hour, int dayStemIndex) {
    final int hourBranchIndex = ((hour + 1) % 24) ~/ 2;
    final int stemStart = (dayStemIndex % 5) * 2;
    final int hourStemIndex = (stemStart + hourBranchIndex) % 10;
    return _buildPillar(hourStemIndex, hourBranchIndex);
  }

  // ─── Wu Xing Balance ────────────────────────────────────────────────────

  /// Counts elemental distribution across stems, branch surfaces, and
  /// Cang Gan (藏干 hidden stems). A full chart yields 16–17 characters.
  static WuXingBalance calculateWuXingBalance(List<BaziPillar?> pillars) {
    int kayu = 0, api = 0, tanah = 0, logam = 0, air = 0;

    void addElement(String el, {int weight = 1}) {
      switch (el) {
        case 'kayu':
          kayu += weight;
          break;
        case 'api':
          api += weight;
          break;
        case 'tanah':
          tanah += weight;
          break;
        case 'logam':
          logam += weight;
          break;
        case 'air':
          air += weight;
          break;
      }
    }

    // Cang Gan weight: main qi=3, middle qi=2, residual qi=1
    int _cangGanWeight(int position, int total) {
      if (total == 1) return 3;
      if (total == 2) return position == 0 ? 3 : 1;
      return 3 - position; // 3, 2, 1
    }

    for (final pillar in pillars) {
      if (pillar == null) continue;
      // Heavenly Stem
      addElement(stemElements[pillar.stemIndex]);
      // Earthly Branch surface element
      addElement(branchElements[pillar.branchIndex]);
      // Cang Gan — weighted: main qi +3, middle qi +2, residual qi +1
      final hiddenList = _branchHiddenStems[pillar.branchIndex];
      for (int i = 0; i < hiddenList.length; i++) {
        addElement(
          stemElements[hiddenList[i]],
          weight: _cangGanWeight(i, hiddenList.length),
        );
      }
    }

    return WuXingBalance(
      kayu: kayu,
      api: api,
      tanah: tanah,
      logam: logam,
      air: air,
    );
  }

